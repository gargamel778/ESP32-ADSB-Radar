def write_inc(txt, inc):
    """tools/icao_ranges.txt -> firmware/src/icao_ranges.inc (the table the radar compiles in)."""
    with open(inc, "w") as f:
        f.write("// Generated by tools/build_icao_ranges.py --inc from tools/icao_ranges.txt (ICAO Annex 10 Vol. III Table 9-1). Do not edit.\n")
        for l in open(txt):
            if l.strip() and not l.startswith("#"):
                a, b, c = l.split()
                f.write(f'{{0x{a}, 0x{b}, "{c}"}},\n')

if len(sys.argv) > 1 and sys.argv[1] == "--inc":
    here = __import__("os").path.dirname(__import__("os").path.abspath(__file__))
    write_inc(here + "/icao_ranges.txt", sys.argv[2] if len(sys.argv) > 2 else here + "/../firmware/src/icao_ranges.inc")
    sys.exit(0)

def parse(path):
    pat = re.compile(r"([01]{4,14}-+)")
    entries, pending = [], []
    for ln in open(path, errors="replace").read().splitlines():
        m = pat.search(ln)
        name = ln[: m.start()].strip() if m else ln.strip()
        name = re.sub(r"\s*\*\s*$", "", name).strip()
        name = re.sub(r"\s+\*.*$", "", name).strip()
        if m:
            if name and not name.startswith("-"):
                entries.append((name, m.group(1)))
            else:
                pending.append(m.group(1))
        elif name and name != "-" and pending and re.match(r"[A-Z]", name):
            entries += [(name, p) for p in pending]
            pending = []
    return entries

def rng(p):
    bits = p.rstrip("-"); n = len(bits)
    base = int(bits, 2) << (24 - n)
    return base, base + (1 << (24 - n)) - 1

rows = []
for name, p in parse(sys.argv[1]):
    if name.startswith("ICAO"):
        a, b = rng(p)
        if a == 0x899000: rows.append((a, b, "TW"))   # Taiwan is allocated out of ICAO's own block
        continue
    if name not in ISO:
        sys.exit(f"unmapped state name: {name}")
    a, b = rng(p)
    rows.append((a, b, ISO[name]))
rows.append((0x516000, 0x5163FF, "ME"))      # Montenegro (newer than the table)
rows.sort()
out = []
