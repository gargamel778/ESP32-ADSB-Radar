#!/usr/bin/env python3
"""Look for personal or identifying data before the project is published.

    python3 tools/privacy_scan.py [folder]        # default: the project itself; use the export folder before publishing

What it looks for:
  - everything listed in tools/pii_denylist.txt (this file is private and is never exported: one literal or /regex/ per line, prefix "text:" for terms that are fine inside the binary data files, e.g. your
    name, e-mail address, board MAC, serial-port number, home coordinates, the radar's PIN);
  - the Wi-Fi name / password and home coordinates found in config/secrets.h (read here, never printed in full);
  - generic leaks: e-mail addresses, MAC addresses, private IPv4 addresses (the setup access point 192.168.4.1 is fine), home-directory paths,
    long key-like tokens, files that should never be published (secrets.h, flash dumps, local PlatformIO config).
Exit status 1 if anything was found. Text files are searched line by line, binary files as raw bytes.
"""
import os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SKIP_DIRS = {".git", ".pio", "__pycache__", "node_modules", "managed_components", ".dummy"}   # generated by the build, not part of the project
BINARY_EXT = {".bin", ".gz", ".png", ".jpg", ".jpeg", ".pdf", ".a", ".o", ".elf", ".zip"}
FORBIDDEN_NAMES = {"secrets.h", "platformio.local.ini", "pii_denylist.txt", ".DS_Store"}
FORBIDDEN_SUFFIX = ("factory-flash",)
GENERIC = [
    ("e-mail address", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"), re.compile(r"@(example\.(com|org)|users\.noreply\.github\.com)$|^you@|^noreply@|^integrationsales@flightaware\.com$")),
    ("MAC address", re.compile(r"\b[0-9A-Fa-f]{2}(?::[0-9A-Fa-f]{2}){5}\b"), re.compile(r"^(00:00:00:00:00:00|xx:xx:xx:xx:xx:xx)$", re.I)),
    ("private IPv4 address", re.compile(r"\b(?:192\.168|10\.\d{1,3}|172\.(?:1[6-9]|2\d|3[01]))\.\d{1,3}\.\d{1,3}\b"), re.compile(r"^192\.168\.4\.1$")),
    ("home-directory path", re.compile(r"/(?:Users|home)/[A-Za-z0-9._-]+/"), re.compile(r"^/(?:Users|home)/(?:you|user|name|yourname)/$")),
    ("key-like token", re.compile(r"\b(?=[A-Za-z0-9]{32,}\b)(?=[A-Za-z0-9]*\d)(?=[A-Za-z0-9]*[a-z])(?=[A-Za-z0-9]*[A-Z])[A-Za-z0-9]{32,}\b"), None),
]


def load_denylist():
    items = []
    p = os.path.join(ROOT, "tools", "pii_denylist.txt")
    if os.path.exists(p):
        for l in open(p, encoding="utf-8"):
            l = l.strip()
            if l and not l.startswith("#"):
                label = "denylist"
                if l.startswith("text:"):   # only for text files: place names that are fine inside the public data files (geo.bin lists every city and zone)
                    label, l = "denylist (text)", l[5:].strip()
                items.append((label, re.compile(l[1:-1], re.I) if l.startswith("/") and l.endswith("/") and len(l) > 2 else re.compile(re.escape(l), re.I)))
    s = os.path.join(ROOT, "config", "secrets.h")
    if os.path.exists(s):
        txt = open(s, encoding="utf-8", errors="replace").read()
        for name in ("WIFI_SSID", "WIFI_PASS"):
            m = re.search(r'#define\s+%s\s+"([^"]*)"' % name, txt)
            if m and len(m.group(1)) >= 4 and m.group(1) not in ("your-wifi-name", "your-wifi-password"):
                items.append((name + " from secrets.h", re.compile(re.escape(m.group(1)))))
        for name in ("HOME_LAT", "HOME_LON"):
            m = re.search(r"#define\s+%s\s+(-?\d+\.\d+)" % name, txt)
            if m and abs(float(m.group(1))) > 0.01:
                v = m.group(1)
                items.append((name + " from secrets.h", re.compile(re.escape(v[: v.index(".") + 4]))))   # first three decimals (~100 m)
    return items


def walk(folder):
    for d, dirs, files in os.walk(folder):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
        for f in files:
            yield os.path.join(d, f)


def main():
    folder = os.path.normpath(sys.argv[1]) if len(sys.argv) > 1 else ROOT
    deny = load_denylist()
    findings = []
    checked = 0
    for path in walk(folder):
        rel = os.path.relpath(path, folder)
        base = os.path.basename(path)
        if folder != ROOT or True:
            if base in FORBIDDEN_NAMES or any(k in base for k in FORBIDDEN_SUFFIX):
                if folder != ROOT:   # in the project itself these files are expected (and git-ignored); in an export they are a leak
                    findings.append((rel, 0, "file that must not be published", base))
                continue
        if rel.startswith(("tests/host/build", "firmware/.pio")):   # build output (git-ignored, never exported)
            continue
        ext = os.path.splitext(base)[1].lower()
        try:
            data = open(path, "rb").read()
        except OSError:
            continue
        checked += 1
        if ext in BINARY_EXT or b"\x00" in data[:4096]:
            for label, rx in deny:
                if label.endswith("(text)"):
                    continue
                if rx.search(data.decode("latin-1")):
                    findings.append((rel, 0, label, "(binary file)"))
            continue
        text = data.decode("utf-8", errors="replace")
        if folder == ROOT and rel in ("config/secrets.h", "firmware/platformio.local.ini", "tools/pii_denylist.txt"):
            continue
        for n, line in enumerate(text.splitlines(), 1):
            for label, rx in deny:
                m = rx.search(line)
                if m:
                    findings.append((rel, n, label, m.group(0)[:1] + "..." + f" ({len(m.group(0))} chars)"))
            for label, rx, ok in GENERIC:
                for m in rx.finditer(line):
                    if ok and ok.search(m.group(0)):
                        continue
                    findings.append((rel, n, label, m.group(0)))
    for f in findings:
        print(f"{f[0]}:{f[1]}: {f[2]}: {f[3]}")
    print(f"\n{checked} files checked in {folder}: {'NOTHING FOUND' if not findings else str(len(findings)) + ' finding(s)'}")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
